-- 一轮只读问数的权威请求、执行与限量交付快照，共用一个原子状态行。
CREATE TABLE qry_request (
    id VARCHAR(36) NOT NULL PRIMARY KEY,
    user_id BIGINT NOT NULL,
    authentication_version BIGINT NOT NULL,
    source_id BIGINT NOT NULL,
    command_id VARCHAR(36) NOT NULL,
    previous_id VARCHAR(36) NULL,
    question VARCHAR(600) NOT NULL,
    clarification VARCHAR(180) NULL,
    supplement VARCHAR(600) NULL,
    clarification_command VARCHAR(36) NULL,
    cancel_requested BOOLEAN NOT NULL DEFAULT FALSE,
    state VARCHAR(40) NOT NULL,
    execution_state VARCHAR(24) NOT NULL DEFAULT 'NOT_SUBMITTED',
    execution_id VARCHAR(36) NULL,
    binding_id BIGINT NULL,
    rule_signature VARCHAR(64) NULL,
    reasoning JSON NULL,
    result JSON NULL,
    remaining_millis INT NOT NULL DEFAULT 120000,
    processing_started_at DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT (UTC_TIMESTAMP(3)),
    updated_at DATETIME(3) NOT NULL DEFAULT (UTC_TIMESTAMP(3)),
    executed_at DATETIME(3) NULL,
    UNIQUE KEY uq_qry_request_command (user_id, command_id),
    UNIQUE KEY uq_qry_execution (execution_id),
    KEY idx_qry_history (user_id, source_id, created_at),
    KEY idx_qry_dispatch (state, updated_at)
);
