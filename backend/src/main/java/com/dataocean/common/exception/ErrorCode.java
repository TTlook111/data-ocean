package com.dataocean.common.exception;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

/**
 * 内部错误目录；HTTP 入参继续使用契约编码，不直接绑定枚举。
 */
@Getter
@RequiredArgsConstructor
public enum ErrorCode {
    VALIDATION_FAILED(400001, 400),
    AUTH_REQUIRED(401001, 401),
    AUTH_EXPIRED(401002, 401),
    AUTH_INVALID_CREDENTIALS(401003, 401),
    CSRF_INVALID(403001, 403),
    PASSWORD_CHANGE_REQUIRED(403002, 403),
    PERMISSION_DENIED(403003, 403),
    GRANT_LIMIT_EXCEEDED(403004, 403),
    PROTECTED_FLOW_REQUIRED(403005, 403),
    RESOURCE_NOT_FOUND(404001, 404),
    VERSION_CONFLICT(409001, 409),
    REVIEW_STALE(409002, 409),
    COMMAND_CONTENT_CONFLICT(409003, 409),
    COMMAND_IN_PROGRESS(409004, 409),
    STATE_CONFLICT(409005, 409),
    REFERENCE_IN_USE(409006, 409),
    IAM_LOGIN_NAME_EXISTS(409101, 409),
    IAM_ROLE_NAME_EXISTS(409102, 409),
    IAM_DEPARTMENT_CODE_EXISTS(409103, 409),
    IAM_LAST_RECOVERY_PATH(409104, 409),
    IAM_DEPARTMENT_CYCLE(409105, 409),
    IAM_PASSWORD_UNCHANGED(409106, 409),
    IAM_CURRENT_PASSWORD_INVALID(400101, 400),
    APPROVAL_ROUTE_STALE(409201, 409),
    APPROVAL_SELF_REVIEW(409202, 409),
    DEPENDENCY_STALE(409301, 409),
    KNOWLEDGE_NOT_READY(409302, 409),
    TASK_TERMINAL(409401, 409),
    STALE_RUN(409402, 409),
    EXECUTION_UNCERTAIN(409403, 409),
    /**
     * 当前来源未获准调用问数模型。
     */
    QUERY_SOURCE_NOT_ADMITTED(409404, 409),
    /**
     * 问数所需的问题理解模型或内部服务配置不可用。
     */
    QUERY_INTENT_UNAVAILABLE(409405, 409),
    RATE_LIMITED(429001, 429),
    CAPACITY_EXCEEDED(429002, 429),
    DEPENDENCY_UNAVAILABLE(503001, 503),
    INTERNAL_ERROR(500001, 500);

    /**
     * 统一业务错误码，与独立的 HTTP 状态分别表达。
     */
    private final int code;

    /**
     * 该业务错误对应的 HTTP 响应状态。
     */
    private final int status;
}
