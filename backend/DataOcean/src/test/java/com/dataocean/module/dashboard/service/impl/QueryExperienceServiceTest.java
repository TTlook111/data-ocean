/** 隔离 H2 运行正式 Mapper 与分页插件，验证两个权限域、计时、分位数和时间边界。 */
class QueryExperienceServiceTest {
    private final IamS1CapabilityService capabilities = mock(IamS1CapabilityService.class);
    private final LocalDateTime yesterday = LocalDate.now().minusDays(1).atStartOfDay();
    private JdbcTemplate jdbc;
    private QueryExperienceServiceImpl service;

    @BeforeEach
    void prepare() throws IOException {
        var source = new UnpooledDataSource("org.h2.Driver", "jdbc:h2:mem:experience_" + UUID.randomUUID()
                + ";MODE=MySQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(source);
        jdbc.execute("""
                CREATE TABLE query_task (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                task_id VARCHAR(50) UNIQUE, user_id BIGINT, datasource_id BIGINT, iam_protocol_version VARCHAR(50),
                status VARCHAR(32), created_at TIMESTAMP, completed_at TIMESTAMP)
                """);
        jdbc.execute("""
                CREATE TABLE governance_feedback (task_id VARCHAR(50), user_id BIGINT, datasource_id BIGINT,
                feedback_type VARCHAR(16), reason_code VARCHAR(32), comment VARCHAR(120), UNIQUE(task_id,user_id))
                """);

        // 从 classpath 加载上线使用的 XML，缺列、错误构造器映射及分页统计条件都应直接失败。
        var config = new MybatisConfiguration();
        config.setEnvironment(new Environment("experience", new SpringManagedTransactionFactory(), source));
        config.addInterceptor(new MyBatisPlusConfig().mybatisPlusInterceptor());
        String xml = "mapper/dashboard/QueryExperienceMapper.xml";
        try (var input = Resources.getResourceAsStream(xml)) {
            new XMLMapperBuilder(input, config, xml, config.getSqlFragments()).parse();
        }
        var session = new SqlSessionTemplate(new MybatisSqlSessionFactoryBuilder().build(config));
        service = new QueryExperienceServiceImpl(session.getMapper(QueryExperienceMapper.class), capabilities);
    }

    @AfterEach
    void release() {
        jdbc.execute("SHUTDOWN");
    }

    @Test
    void measuresOnlyValidCompletionTimesAndComputesNearestRankAcrossUnequalBuckets() {
        scope("audit:view", 1L);
        for (int i = 0; i < 18; i++) task("fast-" + i, 1, "COMPLETED", yesterday.plusMinutes(i), 1);
        task("at-target", 1, "COMPLETED", yesterday.plusHours(13), 10);
        task("slow", 1, "COMPLETED", yesterday.plusHours(13).plusMinutes(1), 40);
        task("negative", 1, "COMPLETED", yesterday.plusHours(13), -5);
        task("missing", 1, "COMPLETED", yesterday.plusHours(13), null);
        for (String status : List.of("FAILED", "TIMEOUT", "CANCELLED", "PROCESSING", "CLARIFICATION_REQUIRED")) {
            task(status, 1, status, yesterday.plusHours(8), 50);
        }
        task("other-source", 2, "COMPLETED", yesterday, 2000);
        task("before", 1, "COMPLETED", yesterday.minusSeconds(1), 2000);
        task("after", 1, "COMPLETED", yesterday.plusDays(1), 2000);
        task("old-protocol", 1, "COMPLETED", yesterday, 2000);
        jdbc.update("UPDATE query_task SET iam_protocol_version=NULL WHERE task_id='old-protocol'");

        QueryExperienceVO overview = service.summary(4L, "yesterday");
        var usage = overview.usage();
        assertThat(overview.feedback()).isNull();
        assertThat(usage.total()).isEqualTo(27);
        assertThat(usage.completed()).isEqualTo(22);
        assertThat(usage.measured()).isEqualTo(20);
        assertThat(usage.avgSeconds()).isEqualTo(3.4);
        assertThat(usage.p95Seconds()).isEqualTo(10L);
        assertThat(usage.slow()).isEqualTo(1);
        assertThat(List.of(usage.failed(), usage.timedOut(), usage.processing(), usage.cancelled(), usage.clarification()))
                .containsOnly(1L);
        assertThat(usage.buckets()).hasSize(24);
        assertThat(usage.buckets().get(2).avgSeconds()).isNull();
        assertThat(usage.buckets().get(13).avgSeconds()).isEqualTo(25.0);
        assertThat(usage.buckets().get(13).start()).isEqualTo(yesterday.plusHours(13));

        // 明细与桶共用严格大于阈值的定义，越权源与恰好十秒的记录均不出现。
        var details = query(overview, "slow");
        details.setBucketStart(yesterday.plusHours(13));
        var page = service.details(4L, details);
        assertThat(page.getTotal()).isEqualTo(1);
        assertThat(page.getRecords()).singleElement().satisfies(row -> {
            assertThat(row.taskId()).isEqualTo("slow");
            assertThat(row.seconds()).isEqualTo(40L);
            assertThat(row.comment()).isNull();
        });
    }

    @Test
    void votesUseTheirOwnSourceScopeTaskOwnerAndCurrentVoteAndReauthorizeEveryDetailRead() {
        scope("governance:field:view", 2L);
        for (int i = 1; i <= 4; i++) task("review-" + i, 2, "COMPLETED", yesterday.plusMinutes(i), 4);
        task("other-source", 1, "COMPLETED", yesterday, 9);
        task("failed", 2, "FAILED", yesterday, 9);
        vote("review-1", 2, 7, "DISLIKE");
        vote("review-2", 2, 7, "DISLIKE");
        vote("review-3", 2, 7, "LIKE");
        vote("other-source", 1, 7, "DISLIKE");
        vote("failed", 2, 7, "DISLIKE");
        vote("review-4", 1, 7, "DISLIKE");
        vote("review-4", 2, 88, "DISLIKE");
        // taskId 是身份标识，排序规则不同或大小写相似都不能将别的反馈归到当前回答。
        vote("REVIEW-3", 2, 7, "DISLIKE");

        var overview = service.summary(4L, "yesterday");
        assertThat(overview.usage()).isNull();
        assertThat(overview.feedback()).isEqualTo(new QueryExperienceVO.Feedback(4, 1, 2, null, null));
        var query = query(overview, "feedback");
        query.setPageSize(1L);
        query.setPageNo(2L);
        var page = service.details(4L, query);
        assertThat(page.getTotal()).isEqualTo(2);
        assertThat(page.getRecords()).singleElement().satisfies(row -> {
            assertThat(row.taskId()).isEqualTo("review-1");
            assertThat(row.comment()).isEqualTo("测试评价");
            assertThat(row.seconds()).isNull();
        });
        jdbc.update("UPDATE governance_feedback SET feedback_type='LIKE' WHERE task_id='review-1'");
        assertThat(service.details(4L, query).getTotal()).isEqualTo(1);

        when(capabilities.responsibleDatasourcesWithFunction(4L, "governance:field:view")).thenReturn(List.of());
        assertThatThrownBy(() -> service.details(4L, query)).isInstanceOfSatisfying(BusinessException.class,
                ex -> assertThat(ex.getCode()).isEqualTo(403));
    }

    @Test
    void dateRangesPreserveEmptySamplesAndRejectBucketOrPeriodSubstitution() {
        scope("audit:view", 1L);
        scope("governance:field:view", 2L);
        var overview = service.summary(4L, "week");
        assertThat(overview.start()).isEqualTo(overview.asOf().toLocalDate().minusDays(6).atStartOfDay());
        assertThat(overview.end()).isEqualTo(overview.asOf());
        assertThat(overview.usage().p95Seconds()).isNull();
        assertThat(overview.usage().avgSeconds()).isNull();
        assertThat(overview.usage().buckets()).allMatch(bucket -> bucket.measured() == 0 && bucket.avgSeconds() == null);
        assertThat(overview.feedback().eligible()).isZero();
        var invalid = query(overview, "slow");
        invalid.setBucketStart(overview.start().plusSeconds(1));
        assertThatThrownBy(() -> service.details(4L, invalid)).isInstanceOf(BusinessException.class);
        invalid.setKind("feedback");
        assertThatThrownBy(() -> service.details(4L, invalid)).isInstanceOf(BusinessException.class);
        assertThatThrownBy(() -> service.summary(4L, "all")).isInstanceOf(BusinessException.class);
    }

    @Test
    void todayUsesTheSameElapsedIntervalYesterdayAndLeavesUnmeasuredDaysUnknown() {
        scope("audit:view", 1L);
        scope("governance:field:view", 2L);
        task("previous-answer", 1, "COMPLETED", yesterday, 12);
        task("previous-vote", 2, "COMPLETED", yesterday, 4);
        vote("previous-vote", 2, 7, "DISLIKE");
        var today = service.summary(4L, "today");
        // 午夜的真实半开区间尚无记录；届时前日同范围也应为空。
        boolean coversFirstSecond = today.start().isBefore(today.asOf());
        assertThat(today.usage().avgSeconds()).isNull();
        assertThat(today.usage().previousAvgSeconds()).isEqualTo(coversFirstSecond ? 12.0 : null);
        assertThat(today.feedback().previousDislikes()).isEqualTo(coversFirstSecond ? 1L : 0L);
        assertThat(today.feedback().previousLikes()).isZero();
    }

    @Test
    void disabledSourceBindingDoesNotExposeVotesOrSlowAnswers() {
        // 普通角色的能力摘要会保留停用来源引用。当前来源 guard 已拒绝这些来源的反馈记录。
        when(capabilities.responsibleDatasourcesWithFunction(4L, "audit:view"))
                .thenReturn(List.of(new IamS1DatasourceRefVO(1L, "停用源", false)));
        when(capabilities.responsibleDatasourcesWithFunction(4L, "governance:field:view"))
                .thenReturn(List.of(new IamS1DatasourceRefVO(1L, "停用源", false)));
        task("disabled", 1, "COMPLETED", yesterday, 20);
        vote("disabled", 1, 7, "DISLIKE");
        var overview = service.summary(4L, "yesterday");
        assertThat(overview.usage()).isNull();
        assertThat(overview.feedback()).isNull();
        assertThatThrownBy(() -> service.details(4L, query(overview, "feedback")))
                .isInstanceOfSatisfying(BusinessException.class, ex -> assertThat(ex.getCode()).isEqualTo(403));
    }

    /** 所有样例只在随机命名的 H2 内存库中生成。 */
    private void task(String id, int source, String status, LocalDateTime start, Integer seconds) {
        jdbc.update("""
                INSERT INTO query_task(task_id,user_id,datasource_id,iam_protocol_version,status,created_at,completed_at)
                VALUES (?,7,?,'IAM-SIMPLE-1',?,?,?)
                """, id, source, status, start, seconds == null ? null : start.plusSeconds(seconds));
    }

    private void vote(String id, int source, int owner, String type) {
        jdbc.update("INSERT INTO governance_feedback VALUES (?,?,?,?,'UNKNOWN','测试评价')", id, owner, source, type);
    }

    private void scope(String function, long source) {
        when(capabilities.responsibleDatasourcesWithFunction(4L, function))
                .thenReturn(List.of(new IamS1DatasourceRefVO(source, "测试源", true)));
    }

    private QueryExperienceDetailsQuery query(QueryExperienceVO overview, String kind) {
        var result = new QueryExperienceDetailsQuery();
        result.setAsOf(overview.asOf());
        result.setPeriod(overview.period());
        result.setKind(kind);
        return result;
    }
}
