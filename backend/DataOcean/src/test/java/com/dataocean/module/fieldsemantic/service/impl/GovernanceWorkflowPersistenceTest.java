    private void create(Class<?> type){
        String table=type.getAnnotation(com.baomidou.mybatisplus.annotation.TableName.class).value();jdbc.execute("DROP TABLE IF EXISTS "+table);
        List<String> definitions=new ArrayList<>();
        for(var field:type.getDeclaredFields()){
            if(Modifier.isStatic(field.getModifiers()))continue;
            var annotation=field.getAnnotation(com.baomidou.mybatisplus.annotation.TableField.class);if(annotation!=null&&!annotation.exist())continue;
            String name=field.getName().replaceAll("([a-z0-9])([A-Z])","$1_$2").toLowerCase();
            String sql=field.getName().equals("id")?"BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY":
                    field.getType()==Long.class?"BIGINT":field.getType()==Integer.class?"INT":field.getType()==Boolean.class?"BOOLEAN":
                    field.getType()==java.time.LocalDateTime.class?"TIMESTAMP":field.getType()==java.math.BigDecimal.class?"DECIMAL(20,6)":"VARCHAR(100000)";
            definitions.add(name+" "+sql);
        }jdbc.execute("CREATE TABLE "+table+"("+String.join(",",definitions)+")");
    }
